package com.example.k_sudoku

import com.example.k_sudoku.domain.model.SudokuBoard
import com.example.k_sudoku.domain.model.SudokuDifficulty
import com.example.k_sudoku.domain.usecase.GenerateSudokuUseCase
import com.example.k_sudoku.domain.usecase.SolveSudokuUseCase
import com.example.k_sudoku.presentation.viewmodel.SudokuViewModel
import io.kotest.core.spec.style.BehaviorSpec
import io.kotest.matchers.shouldBe
import io.mockk.coEvery
import io.mockk.mockk

class SudokuViewModelTest : BehaviorSpec( {

    val generateUseCase = mockk<GenerateSudokuUseCase>()
    val solveUseCase = mockk<SolveSudokuUseCase>()

    val emptyCells = List(9) { MutableList(9){0} }
    val initialFlags = List(9) { MutableList(9){false} }
    val testBoard = SudokuBoard(cells = emptyCells, initialFlags)

    beforeTest {
        coEvery { generateUseCase(any()) } returns testBoard
    }

    Given("SudokuViewModel is initialized"){
        val viewModel = SudokuViewModel(generateUseCase, solveUseCase)

        When("user changes the cell value"){
            viewModel.onCellChanged(row = 0, col = 0, value = 3)

            Then("the cell in boardState should be updated to 3"){
                viewModel.boardState.value.cells[0][0] shouldBe 3
            }
        }

        When("timer is paused and user edits a cell"){
            viewModel.pauseTimer()
            viewModel.isPaused.value shouldBe true
            viewModel.onCellChanged(0,1,5)

            Then("timer should automatically resume"){
                viewModel.isPaused.value shouldBe false
                viewModel.boardState.value.cells[0][1] shouldBe 5
            }
        }

        When("user tries to edit an initial cell"){
            val initialBoard=testBoard.copy(
                cells = testBoard.cells.also { it[0][0] = 7 },
                initial = testBoard.initial.also { it[0][0] = true }
            )
            coEvery { generateUseCase(any()) } returns initialBoard
            val vm = SudokuViewModel(generateUseCase, solveUseCase)

            vm.onCellChanged(0,0,9)

            Then("the initial cell value should not be changed"){
                vm.boardState.value.cells[0][0] shouldBe 7
            }
        }

        When("user resets game with HARD difficulty"){
            viewModel.resetGame(SudokuDifficulty.HARD)

            Then("hints and flags should reset for hard difficulty"){
                viewModel.remainingHints.value shouldBe SudokuDifficulty.HARD.maxHintsAllowed
                viewModel.isGeneratedByComputer.value shouldBe false
                viewModel.elapsedTime.value shouldBe 0L
            }
        }

        When("user requests computer to solve the board"){
            val solvedBoard=testBoard.copy()
            coEvery { solveUseCase(any()) } returns solvedBoard

            viewModel.solveBoard()

            Then("isGenerated by computer sholud be true"){
                viewModel.isGeneratedByComputer.value shouldBe true
                viewModel.boardState.value shouldBe solvedBoard
            }
        }

        When("user opens options menu (3 dots)"){
            viewModel.pauseTimer()

            Then("timer should be paused"){
                viewModel.isPaused.value shouldBe true
            }
        }

        When("user requests the hint"){
            val initialHints = viewModel.remainingHints.value
            viewModel.provideHint()

            Then("remaining hints count should decrease"){
                viewModel.remainingHints.value shouldBe (initialHints-1)
            }
        }

        When("user requests hint when remaining hints is 0"){
            while(viewModel.remainingHints.value > 0){
                viewModel.provideHint()
            }
            viewModel.provideHint()

            Then("remaining hints should stay 0"){
                viewModel.remainingHints.value shouldBe 0
            }
        }

        When("togglePause is called"){
            viewModel.pauseTimer()
            viewModel.togglePause()

            Then("isPaused should toggle to false"){
                viewModel.isPaused.value shouldBe false
            }

            viewModel.togglePause()

            Then("isPaused should toggle back to true"){
                viewModel.isPaused.value shouldBe true
            }
        }

        When("user pauses the timer"){
            viewModel.pauseTimer()

            Then("isPaused should be true"){
                viewModel.isPaused.value shouldBe true
            }
        }

        When("user resumes the timer"){
            viewModel.resumeTimer()

            Then("isPaused should be false"){
                viewModel.isPaused.value shouldBe false
            }
        }

        When("resetTimer is called"){
            viewModel.resetTimer()

            Then("elapsed time should be 0 and isPaused false"){
                viewModel.elapsedTime.value shouldBe 0L
                viewModel.isPaused.value shouldBe false
            }
        }

    }

})